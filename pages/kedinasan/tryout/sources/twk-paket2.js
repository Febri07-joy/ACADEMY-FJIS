/*
==========================================================
VALIDASI BANK SOAL PAKET 2
==========================================================
*/

(function validateTWKPaket2() {

  const questions = window.TWK_PAKET2;

  if (!Array.isArray(questions)) {
    console.error(
      "[TWK Paket 2] Bank soal tidak ditemukan."
    );
    return;
  }

  if (questions.length !== 30) {
    console.warn(
      `[TWK Paket 2] Seharusnya 30 soal, sekarang ${questions.length}.`
    );
  }

  const ids = new Set();

  questions.forEach((question, index) => {

    if (!question.id) {
      console.error(
        `[TWK Paket 2] Soal ${index + 1} tidak memiliki ID.`
      );
    }

    if (ids.has(question.id)) {
      console.error(
        `[TWK Paket 2] ID duplikat: ${question.id}`
      );
    }

    ids.add(question.id);

    const keys =
      Object.keys(question.options || {});

    if (
      keys.length !== 5 ||
      !["A", "B", "C", "D", "E"].every(
        key => keys.includes(key)
      )
    ) {

      console.error(
        `[TWK Paket 2] Opsi soal ${question.id} tidak lengkap.`
      );

    }

    if (
      !["A", "B", "C", "D", "E"].includes(
        question.correct
      )
    ) {

      console.error(
        `[TWK Paket 2] Kunci soal ${question.id} tidak valid.`
      );

    }

    if (!question.explanation) {

      console.warn(
        `[TWK Paket 2] ${question.id} belum memiliki pembahasan.`
      );

    }

  });

  console.log(
    `[TWK Paket 2] ${questions.length} soal berhasil dimuat.`
  );

})();