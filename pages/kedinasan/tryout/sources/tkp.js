// VALIDASI DATA TKP
// ============================================================

(function validateTKP() {

  if (!Array.isArray(window.TKP_QUESTIONS)) {
    console.error("TKP_QUESTIONS tidak ditemukan.");
    return;
  }

  window.TKP_QUESTIONS.forEach((question, index) => {

    if (!question.id) {
      console.warn(`TKP soal ke-${index + 1} tidak memiliki ID.`);
    }

    if (!question.question) {
      console.warn(`TKP ${question.id} tidak memiliki pertanyaan.`);
    }

    if (
      !Array.isArray(question.options) ||
      question.options.length !== 5
    ) {
      console.warn(
        `TKP ${question.id} harus memiliki tepat 5 opsi.`
      );
      return;
    }

    question.options.forEach((option, optionIndex) => {

      if (!option.k || !option.t) {
        console.warn(
          `TKP ${question.id}: opsi ${optionIndex + 1} tidak lengkap.`
        );
      }

      if (
        typeof option.score !== "number" ||
        option.score < 1 ||
        option.score > 5
      ) {
        console.warn(
          `TKP ${question.id}: skor opsi ${option.k} harus 1-5.`
        );
      }

    });

  });

  console.log(
    `TKP berhasil dimuat: ${window.TKP_QUESTIONS.length} soal`
  );

})();