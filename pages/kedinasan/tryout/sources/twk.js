// VALIDASI DATA TWK
// ============================================================

(function validateTWK() {

  if (!Array.isArray(window.TWK_QUESTIONS)) {
    console.error("TWK_QUESTIONS tidak ditemukan.");
    return;
  }

  window.TWK_QUESTIONS.forEach((question, index) => {

    if (!question.id) {
      console.warn(`TWK soal ke-${index + 1} tidak memiliki ID.`);
    }

    if (!question.question) {
      console.warn(`TWK ${question.id} tidak memiliki pertanyaan.`);
    }

    if (
      !question.options ||
      typeof question.options !== "object" ||
      Array.isArray(question.options)
    ) {
      console.warn(`TWK ${question.id} memiliki options yang tidak valid.`);
    }

    if (!question.correct) {
      console.warn(`TWK ${question.id} belum memiliki kunci jawaban.`);
    }

    if (
      question.options &&
      !Object.prototype.hasOwnProperty.call(
        question.options,
        question.correct
      )
    ) {
      console.warn(
        `TWK ${question.id}: kunci ${question.correct} tidak ditemukan di options.`
      );
    }

  });

  console.log(
    `TWK berhasil dimuat: ${window.TWK_QUESTIONS.length} soal`
  );

})();