// ============================================================
// VALIDASI DATA TIU
// ============================================================

(function validateTIU() {

  if (!Array.isArray(window.TIU_QUESTIONS)) {
    console.error("TIU_QUESTIONS tidak ditemukan.");
    return;
  }

  window.TIU_QUESTIONS.forEach((question, index) => {

    if (!question.id) {
      console.warn(
        `TIU soal ke-${index + 1} tidak memiliki ID.`
      );
    }

    if (!question.question) {
      console.warn(
        `TIU ${question.id} tidak memiliki pertanyaan.`
      );
    }

    if (
      !question.options ||
      typeof question.options !== "object"
    ) {
      console.warn(
        `TIU ${question.id} memiliki options yang tidak valid.`
      );
    }

    if (!question.correct) {
      console.warn(
        `TIU ${question.id} belum memiliki kunci jawaban.`
      );
    }

    if (
      question.options &&
      !Object.prototype.hasOwnProperty.call(
        question.options,
        question.correct
      )
    ) {
      console.warn(
        `TIU ${question.id}: kunci ${question.correct} tidak ditemukan di options.`
      );
    }

  });

  console.log(
    `TIU berhasil dimuat: ${window.TIU_QUESTIONS.length} soal`
  );

})();