(function validateTKPPaket2(){
  const bank = window.TKP_PAKET2;
  const bad = [];
  const ids = new Set();

  bank.forEach(q=>{
    if(ids.has(q.id)) bad.push(`${q.id}: duplicate id`);
    ids.add(q.id);
    if(!Array.isArray(q.options) || q.options.length !== 5)
      bad.push(`${q.id}: harus punya 5 opsi`);
    if(!Array.isArray(q.score) || q.score.length !== 5)
      bad.push(`${q.id}: score harus berisi 5 nilai`);
    if(Array.isArray(q.score) && q.score.some(v=>![1,2,3,4,5].includes(v)))
      bad.push(`${q.id}: score harus 1–5`);
  });

  if(bank.length !== 45) bad.push(`Jumlah soal ${bank.length}, seharusnya 45`);

  console.log("TKP Paket 2 dimuat:", bank.length, "soal");
  if(bad.length) console.error("Audit TKP Paket 2:", bad);
  else console.log("Audit struktur TKP Paket 2: OK (45 soal, 5 opsi, skor 1–5).");
})();
